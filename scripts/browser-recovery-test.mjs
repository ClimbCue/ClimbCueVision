import { chromium } from 'playwright';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.CLIMBCUE_TEST_URL||'http://127.0.0.1:8000';
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({channel:process.env.CLIMBCUE_BROWSER||'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(base+'/knowledge');
 await page.waitForFunction(()=>document.querySelector('#total').textContent==='109');
 await page.click('[data-library="recovery"]');
 assert.equal(await page.locator('#library .library-item').count(),76);
 assert.equal(await page.locator('#library-count').textContent(),'76 条资料');
 await page.click('[data-query="前臂拉伸"]');
 await page.waitForFunction(()=>document.querySelector('#answer').textContent.includes('前臂外侧'));
 assert.equal(await page.inputValue('#category-filter'),'recovery');
 assert.match(await page.locator('#answer').textContent(),/kb\.recovery-aaos-elbow/);
 const downloading=page.waitForEvent('download');
 await page.locator('#results a[download]').first().click();
 const download=await downloading;
 await download.saveAs('artifacts/recovery-document.md');
 const doc=await readFile('artifacts/recovery-document.md','utf8');
 assert.match(doc,/AAOS/);assert.match(doc,/适用范围与限制/);
 await page.click('[data-query="攀后酸痛"]');
 await page.waitForFunction(()=>document.querySelector('#answer').textContent.includes('临床上重要的效果'));
 await page.screenshot({path:'artifacts/recovery-desktop.png'});
 await page.fill('#question','宇宙飞船发动机设计');await page.click('#ask');
 await page.waitForFunction(()=>document.querySelector('#query-status').textContent.includes('找到 0'));
 await page.click('[data-query="睡眠恢复"]');
 await page.waitForFunction(()=>document.querySelector('#answer').textContent.includes('七至九小时'));
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.screenshot({path:'artifacts/recovery-mobile.png'});
 await page.locator('#query-status').scrollIntoViewIfNeeded();
 await page.screenshot({path:'artifacts/recovery-mobile-answer.png'});
 // Original shortcut resets the recovery-only filter; videos remain accessible.
 await page.click('[data-query="读线视频"]');
 await page.waitForFunction(()=>document.querySelector('#results').textContent.includes('视频入口'));
 assert.equal(await page.inputValue('#category-filter'),'');
 await page.click('[data-library="video"]');
 assert.equal(await page.locator('#library .library-item').count(),9);
 const stats=await(await page.request.get(base+'/api/knowledge/stats')).json();
 assert.equal(stats.total,109);assert.equal(stats.eligible,108);
 assert.deepEqual(errors,[]);
 const report={passed:true,stats,recovery_cards:76,downloaded_document:download.suggestedFilename(),checks:['recovery shelf','topic filter','forearm citations','document download','soreness evidence','unknown question abstention','sleep query','mobile no horizontal overflow','video regression'],browser_errors:errors};
 await writeFile('artifacts/recovery-browser-report.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
